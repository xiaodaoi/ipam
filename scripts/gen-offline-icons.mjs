#!/usr/bin/env node
// 生成离线 iconify 图标集合（M6-018）。
//
// 扫描 IPAM 前端与 Vben 上游源码中按名引用的 iconify 图标（形如 `lucide:eye`），
// 从构建期依赖 @iconify/json（MIT）中提取用到的图标子集，产出可在运行期
// addCollection 注册的离线集合，从而彻底摆脱 api.iconify.design 外部 CDN。
//
// 用法：
//   node scripts/gen-offline-icons.mjs           # 生成
//   node scripts/gen-offline-icons.mjs --check   # 校验已提交文件是否为最新（CI 门禁）
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const web = join(root, 'web');

// @iconify/json 由 packages/@core/base/design 声明（pnpm 严格依赖），经其解析取包。
const designReq = createRequire(join(web, 'packages/@core/base/design/package.json'));
const iconifyJsonDir = dirname(designReq.resolve('@iconify/json/package.json'));

const outFile = join(web, 'apps/web-ipam/src/icons/offline-icons.generated.ts');

// 参与扫描的源码目录（排除产物/依赖）。
const scanRoots = [join(web, 'apps/web-ipam/src'), join(web, 'packages')];
const skipDirs = new Set(['node_modules', 'dist', '.turbo', '.cache', 'coverage']);

// 合法集合前缀表（collections.json），用于过滤非图标 token（如权限域 dhcp:read）。
const collections = JSON.parse(readFileSync(join(iconifyJsonDir, 'collections.json'), 'utf8'));
const validPrefixes = new Set(Object.keys(collections));

const tokenRe = /\b([a-z][a-z0-9]*(?:-[a-z0-9]+)*):([a-z][a-z0-9]*(?:-[a-z0-9]+)*)\b/g;

/** 递归遍历目录，返回参与扫描的文本文件路径。 */
function walk(dir, acc = []) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return acc;
  }
  for (const name of entries) {
    if (skipDirs.has(name)) continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) {
      walk(p, acc);
    } else if (/\.(?:ts|tsx|vue|mts|js|mjs|json)$/.test(name)) {
      acc.push(p);
    }
  }
  return acc;
}

/** 扫描所有源码，返回 prefix -> Set(iconName)。 */
function scanIcons() {
  const found = new Map();
  for (const dir of scanRoots) {
    for (const file of walk(dir)) {
      const text = readFileSync(file, 'utf8');
      let m;
      tokenRe.lastIndex = 0;
      while ((m = tokenRe.exec(text)) !== null) {
        const [, prefix, name] = m;
        if (!validPrefixes.has(prefix)) continue;
        if (!found.has(prefix)) found.set(prefix, new Set());
        found.get(prefix).add(name);
      }
    }
  }
  return found;
}

/** 从完整集合中提取子集，并递归解析 alias 依赖的父图标。 */
function subset(set, names) {
  const icons = {};
  const aliases = {};
  const add = (name, seen) => {
    if (icons[name] || aliases[name] || seen.has(name)) return;
    seen.add(name);
    if (set.icons[name]) {
      icons[name] = set.icons[name];
      return;
    }
    const alias = set.aliases && set.aliases[name];
    if (alias) {
      aliases[name] = alias;
      if (alias.parent) add(alias.parent, seen);
    }
  };
  for (const n of names) add(n, new Set());
  const out = { prefix: set.prefix, icons, aliases, width: set.width, height: set.height };
  if (set.info) out.info = set.info;
  return out;
}

function build() {
  const found = scanIcons();
  const result = [];
  const missing = [];
  for (const prefix of [...found.keys()].sort()) {
    const names = [...found.get(prefix)].sort();
    let set;
    try {
      set = JSON.parse(readFileSync(join(iconifyJsonDir, 'json', `${prefix}.json`), 'utf8'));
    } catch {
      missing.push(`${prefix}:* (集合缺失)`);
      continue;
    }
    const sub = subset(set, names);
    for (const n of names) {
      if (!sub.icons[n] && !sub.aliases[n]) missing.push(`${prefix}:${n}`);
    }
    result.push(sub);
  }
  return { result, missing };
}

function render(sets) {
  const header = [
    '// AUTO-GENERATED by scripts/gen-offline-icons.mjs — 请勿手改。',
    '// 运行 `node scripts/gen-offline-icons.mjs` 重新生成。',
    '// 由 @iconify/json 提取的离线图标子集，供应用启动时 addCollection 注册，避免访问外部 CDN。',
    '// 不引入类型依赖：由调用方按 addCollection 参数类型断言（见 icons/offline.ts）。',
    '',
    'export const offlineIconCollections: unknown[] = ',
  ].join('\n');
  return `${header}${JSON.stringify(sets)}\n;\n`;
}

const { result, missing } = build();
if (missing.length > 0) {
  console.error('⚠️  以下图标未能从 @iconify/json 解析（可能是拼写错误或动态拼接）：');
  for (const m of missing) console.error(`   - ${m}`);
}
const output = render(result);
const totalIcons = result.reduce((n, s) => n + Object.keys(s.icons || {}).length, 0);
const totalPrefixes = result.length;

const mode = process.argv[2] || '';
if (mode === '--check') {
  let current = '';
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {
    console.error(`FAIL: ${relative(root, outFile)} 不存在，请运行 node scripts/gen-offline-icons.mjs`);
    process.exit(1);
  }
  if (current !== output) {
    console.error('FAIL: 离线图标集合与源码不一致——请运行 node scripts/gen-offline-icons.mjs 后提交');
    process.exit(1);
  }
  console.log(`OK: 离线图标集合是最新的（${totalPrefixes} 集合 / ${totalIcons} 图标）`);
  process.exit(0);
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, output);
console.log(`OK: 已生成 ${relative(root, outFile)}（${totalPrefixes} 集合 / ${totalIcons} 图标，${(output.length / 1024).toFixed(1)} KiB）`);
